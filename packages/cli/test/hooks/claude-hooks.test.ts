import { afterEach, describe, expect, it } from "bun:test";
import { join } from "node:path";
import { PROXY_VARIABLES, RUNTIME_VARIABLES, TRUST_VARIABLES } from "@snagentic/core";
import { runCli } from "../../src/cli/run-cli";
import { runClaudeHook } from "../../src/hooks/claude-hooks";
import { hookOutcome } from "../../src/hooks/hook-command";
import { USE_CASES } from "../../src/registry/registry";
import { captureIo, FAKE_CONTEXT } from "../support/fakes";
import { instanceWorkspace } from "../support/instance-workspace";

const finding = (severity: string) => ({
  ruleId: "SN-SEC-001",
  severity,
  path: "source/global/src/fluent/x.server.js",
  line: 2,
  message: "eval() executes arbitrary strings as code",
  remediation: "Call the function directly.",
});
const edit = { tool_input: { file_path: "/w/instances/pdi/metadata/global/x.script.js" } };

describe("Claude Code hooks", () => {
  it("blocks an edit to a protected file before it happens, with the reason", async () => {
    const outcome = await runClaudeHook("pre-edit", edit, async (name, input) => {
      expect([name, input]).toEqual(["check", { paths: [edit.tool_input.file_path] }]);
      return { protected: [{ path: "x", reason: "the mirror is read-only" }], passed: false };
    });
    expect(outcome).toEqual({
      exitCode: 2,
      stdout: "",
      stderr: "snagentic: do not edit this file. x: the mirror is read-only",
    });
    expect(await runClaudeHook("pre-edit", edit, async () => ({ protected: [] }))).toMatchObject({
      exitCode: 0,
    });
  });

  it("blocks after an edit that wrote a protected file, such as a new one in the mirror", async () => {
    const written = await runClaudeHook("post-edit", edit, async () => ({
      protected: [
        { path: "instances/pdi/metadata/global/x.yaml", reason: "the mirror is read-only" },
      ],
    }));
    expect(written.exitCode).toBe(2);
    expect(written.stderr).toContain(
      "instances/pdi/metadata/global/x.yaml: the mirror is read-only",
    );
    expect(await runClaudeHook("post-edit", edit, async () => ({ protected: [] }))).toEqual({
      exitCode: 0,
      stdout: "",
      stderr: "",
    });
  });

  it("keeps the agent working while validate blocks, but only once per stop", async () => {
    const run = async () => ({ findings: [finding("block")] });
    const outcome = await runClaudeHook("stop", {}, run);
    expect(JSON.parse(outcome.stdout)).toMatchObject({
      decision: "block",
      reason: expect.stringContaining("SN-SEC-001"),
    });
    expect(await runClaudeHook("stop", { stop_hook_active: true }, run)).toEqual({
      exitCode: 0,
      stdout: "",
      stderr: "",
    });
    expect(
      await runClaudeHook("stop", {}, async () => ({ findings: [finding("warn")] })),
    ).toMatchObject({ stdout: "" });
  });

  it("never stops the agent over its own failure, or an event without a file", async () => {
    const failed = await runClaudeHook("post-edit", edit, async () => {
      throw new Error("no workspace here");
    });
    expect(failed).toEqual({
      exitCode: 0,
      stdout: "",
      stderr: "snagentic hook skipped: no workspace here",
    });
    expect(await runClaudeHook("post-edit", {}, async () => ({}))).toEqual({
      exitCode: 0,
      stdout: "",
      stderr: "",
    });
  });
});

describe("hooks under other hosts", () => {
  const checked = (paths: string[]) => async (name: string, input: Record<string, unknown>) => {
    expect(name).toBe("check");
    paths.push(...(Array.isArray(input["paths"]) ? input["paths"].map(String) : []));
    return { protected: [{ path: "x", reason: "read-only" }], findings: [] };
  };

  it("checks every file in a Copilot CLI apply_patch edit, resolved against the session folder", async () => {
    const paths: string[] = [];
    const outcome = await runClaudeHook(
      "pre-edit",
      {
        hook_event_name: "PreToolUse",
        cwd: "/w",
        tool_name: "Edit",
        tool_input:
          "*** Begin Patch\n*** Add File: snagentic.yaml\n+x\n*** Update File: /w/a.js\n*** Move to: .snagentic/b.js\n@@\n-a\n+b\n*** Delete File: c.yaml\n*** End Patch\n",
      },
      checked(paths),
    );
    expect(outcome.exitCode).toBe(2);
    expect(paths).toEqual(["/w/snagentic.yaml", "/w/a.js", "/w/.snagentic/b.js", "/w/c.yaml"]);
  });

  it("reads the edited path from path, filePath and camelCase toolArgs payloads", async () => {
    for (const payload of [
      { tool_name: "create", tool_input: { path: "/w/snagentic.yaml" } },
      { tool_name: "editFiles", tool_input: { filePath: "/w/snagentic.yaml" } },
      { toolName: "edit", toolArgs: JSON.stringify({ path: "/w/snagentic.yaml" }) },
    ]) {
      const paths: string[] = [];
      expect((await runClaudeHook("pre-edit", payload, checked(paths))).exitCode).toBe(2);
      expect(paths).toEqual(["/w/snagentic.yaml"]);
    }
  });

  it("leaves reads alone when a host runs the edit hook for every tool", async () => {
    const outcome = await runClaudeHook(
      "pre-edit",
      { tool_name: "Read", tool_input: { file_path: "/w/snagentic.yaml" } },
      async () => {
        throw new Error("must not check a read");
      },
    );
    expect(outcome).toEqual({ exitCode: 0, stdout: "", stderr: "" });
  });
});

describe("pre-shell hook", () => {
  const shell = (command: string, tool_name = "Bash") => ({ tool_name, tool_input: { command } });
  const never = async (): Promise<Record<string, unknown>> => {
    throw new Error("a shell hook needs no use case");
  };

  it("refuses commands that bypass snagentic or skip the git hooks", async () => {
    for (const command of [
      "curl -u admin https://dev1.service-now.com/api/now/table/sys_script",
      "cd x && wget https://example.com",
      "git commit --no-verify -m wip",
      "git commit -anm wip",
      "git -c core.hooksPath=/dev/null push",
      "python3 -c 'import requests; requests.get(\"https://dev1.service-now.com\")'",
      "env FOO=1 curl https://example.com",
      "snagentic auth login prod",
      "echo pw | snagentic  auth logout prod",
      "SNAGENTIC_PROD_KIND=development snagentic pull --instance prod",
      "export SNAGENTIC_PROD_URL=evil",
      "SNAGENTIC_PROD_USERNAME=alice snagentic push --instance prod",
      "snagentic upgrade",
      "cd ~ && snagentic upgrade --version 1.0.0",
      "security find-generic-password -s snagentic -w",
      "security dump-keychain",
      "secret-tool lookup service snagentic",
      "cmdkey /list",
      "security add-generic-password -U -s snagentic -a identity:pdi -w x",
      "security delete-generic-password -s snagentic -a admin@dev1.service-now.com",
      "secret-tool store --label=x service snagentic",
      // These make the snagentic binary run other code, or stop checking certificates.
      "BUN_BE_BUN=1 snagentic -e 'console.log(1)'",
      "export BUN_OPTIONS='--preload ./x.ts'",
      "env NODE_OPTIONS=--require=./x.js snagentic pull",
      "NODE_TLS_REJECT_UNAUTHORIZED=0 snagentic pull --instance pdi",
      // These send instance traffic through another host, or trust other certificates.
      "HTTPS_PROXY=http://127.0.0.1:8080 snagentic pull --instance pdi",
      "export https_proxy=http://127.0.0.1:8080",
      "env ALL_PROXY=socks5://127.0.0.1:1080 snagentic mcp",
      "export no_proxy= && snagentic pull",
      "NODE_EXTRA_CA_CERTS=./ca.pem snagentic pull",
      "export SSL_CERT_FILE=/tmp/ca.pem",
      "SSL_CERT_DIR=/tmp/certs snagentic pull",
      "NODE_USE_SYSTEM_CA=1 snagentic pull",
    ]) {
      const outcome = await runClaudeHook("pre-shell", shell(command), never);
      expect([command, outcome.exitCode]).toEqual([command, 2]);
      expect(outcome.stderr).toStartWith("snagentic:");
    }
  });

  it("refuses setting every variable doctor reports as network or runtime", async () => {
    const names = [...PROXY_VARIABLES, ...TRUST_VARIABLES, ...RUNTIME_VARIABLES];
    for (const name of [...names, ...PROXY_VARIABLES.map((n) => n.toLowerCase())]) {
      const outcome = await runClaudeHook("pre-shell", shell(`${name}=x snagentic pull`), never);
      expect([name, outcome.exitCode]).toEqual([name, 2]);
    }
  });

  it("lets ordinary commands and non-shell tools through", async () => {
    for (const payload of [
      shell("bun test"),
      shell("git commit -m 'curly braces'"),
      shell("snagentic pull --instance pdi"),
      shell("echo $HTTPS_PROXY"),
      shell("MY_HTTPS_PROXY_NOTE=x bun test"),
      shell("curl https://example.com", "Read"),
      {},
    ]) {
      expect(await runClaudeHook("pre-shell", payload, never)).toEqual({
        exitCode: 0,
        stdout: "",
        stderr: "",
      });
    }
  });
});

describe("snagentic hook claude", () => {
  const cleanups: (() => Promise<void>)[] = [];
  afterEach(async () => {
    await Promise.all(cleanups.splice(0).map((cleanup) => cleanup()));
  });

  it("refuses an edit to the mirror in a real workspace, naming what to do instead", async () => {
    const ws = await instanceWorkspace({});
    cleanups.push(ws.cleanup);
    const file = join(
      ws.root,
      "instances/pdi/metadata/global/sys_script_include/util--0123456789abcdef0123456789abcdef.script.js",
    );
    const io = captureIo();
    const payload = JSON.stringify({ tool_input: { file_path: file } });
    const exitCode = await runCli(
      ["hook", "claude", "pre-edit", "--workspace", ws.root],
      USE_CASES,
      ws.context,
      io,
      {
        version: "test",
        serveMcp: async () => {},
        readStdin: async () => payload,
      },
    );
    expect(exitCode).toBe(2);
    expect(io.err()).toContain("snagentic adopt");
  });

  async function hook(event: string, stdin: string, useCases = USE_CASES) {
    const io = captureIo();
    const exitCode = await runCli(["hook", "claude", event], useCases, FAKE_CONTEXT, io, {
      version: "test",
      serveMcp: async () => {},
      readStdin: async () => stdin,
    });
    return { exitCode, err: io.err() };
  }

  it("lets the agent go on when the host sends input that is not JSON", async () => {
    expect(await hook("pre-edit", "not json")).toEqual({ exitCode: 0, err: "" });
  });

  it("skips, without stopping the agent, when the command it runs is not registered", async () => {
    const payload = JSON.stringify(edit);
    const outcome = await hook("pre-edit", payload, []);
    expect(outcome.exitCode).toBe(0);
    expect(outcome.err).toContain("snagentic hook skipped: no check command");
  });

  it("ignores an event it does not know", async () => {
    const outcome = await hookOutcome("session-start", edit, async () => {
      throw new Error("must not run");
    });
    expect(outcome).toEqual({ exitCode: 0, stdout: "", stderr: "" });
  });
});
