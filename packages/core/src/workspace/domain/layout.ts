import type { InstanceName } from "../../kernel/instance-name";
import { PULL_CATALOG_FILE, PULL_STATE_FILE } from "../../sync/domain/pull-state";
import { OtherInstancePathError } from "./errors";

// Paths are relative to the workspace root and always use "/" (ADR-0014).
export interface InstancePaths {
  readonly root: string;
  readonly profile: string;
  readonly metadata: string;
  readonly updateSets: string;
  readonly operational: string;
  // The state and catalog each mirror commit was pulled with (ADR-0052).
  readonly pullState: string;
  readonly pullCatalog: string;
  readonly localState: string;
  // Update set exports by default: inside local state, which the workspace never commits.
  readonly exports: string;
  readonly remoteBranch: string;
}

// The workspace's local state, never committed: each instance's under <dir>/<name>/, and the
// workspace's own lock (an instance name has no ".", so workspace.lock is never an instance).
export const LOCAL_STATE_DIR = ".snagentic";

export function instancePaths(name: InstanceName): InstancePaths {
  const root = `instances/${name}`;
  return {
    root,
    profile: `${root}/instance.yaml`,
    metadata: `${root}/metadata`,
    updateSets: `${root}/update-sets`,
    operational: `${root}/operational`,
    pullState: `${root}/${PULL_STATE_FILE}`,
    pullCatalog: `${root}/${PULL_CATALOG_FILE}`,
    localState: `${LOCAL_STATE_DIR}/${name}`,
    exports: `.snagentic/${name}/exports`,
    remoteBranch: `servicenow-remote/${name}`,
  };
}

const INSTANCE_METADATA = /^instances\/([^/]+)\/metadata\//;

export const GITIGNORE = [
  "# Generated by snagentic (ADR-0014).",
  "# Local state: sync state, indexes, locks and caches.",
  ".snagentic/",
  "# Never commit secrets.",
  ".env",
  ".env.*",
  "*.pem",
  "*.key",
  "",
].join("\n");

// A path to a record's file as the mirror names it (relative to instances/<name>/metadata),
// given relative to it, to the workspace, or as an absolute path inside the workspace. A path
// into another instance's metadata is refused: the caller asked about `name`. Windows paths are
// read with / separators, as the mirror names its files everywhere.
export function metadataPath(name: InstanceName, workspace: string, given: string): string {
  const root = workspace.replaceAll("\\", "/");
  const path = given.replaceAll("\\", "/");
  let relative = path.startsWith(`${root}/`) ? path.slice(root.length + 1) : path;
  relative = relative.startsWith("./") ? relative.slice(2) : relative;
  const named = INSTANCE_METADATA.exec(relative);
  if (named?.[1] !== undefined && named[1] !== name) {
    throw new OtherInstancePathError(given, named[1], name);
  }
  return named === null ? relative : relative.slice(named[0].length);
}

// Fluent projects live in the workspace under source/<scope>/ (ADR-0028).
export const FLUENT_SOURCE_DIR = "source";

// A path under source/<scope>/, relative to the workspace, or null for any other path. A `.`,
// `..` or empty segment is refused, so `source/..` can't name the workspace or anything above it.
// Windows paths are read with / separators: snagentic names workspace files with / everywhere.
export function fluentSourcePath(workspace: string, given: string): string | null {
  const root = workspace.replaceAll("\\", "/");
  const path = given.replaceAll("\\", "/");
  let relative = path.startsWith(`${root}/`) ? path.slice(root.length + 1) : path;
  relative = relative.startsWith("./") ? relative.slice(2) : relative;
  const [top, ...rest] = (relative.endsWith("/") ? relative.slice(0, -1) : relative).split("/");
  const plain = rest.length > 0 && rest.every((s) => s !== "" && s !== "." && s !== "..");
  return top === FLUENT_SOURCE_DIR && plain ? relative : null;
}
