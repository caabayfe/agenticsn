import { describe, expect, it } from "bun:test";
import { coalesceValues, compareUnit, knownLoss, unitName } from "@snagentic/core";
import { copy, listCopy, record, revocationList, scriptInclude, unit } from "./units";

const INSTANCE_SCRIPT_INCLUDE = {
  sys_id: "123833b4d97d48be8e9ec5ea16f27764",
  sys_scope: "489da54ae67c4a3e9f1e1e4347e9119b",
  sys_mod_count: "1",
  active: "true",
  api_name: "x_2222332_s11.E2EUtil",
  caller_access: "",
  client_callable: "false",
  description: "Helpers for the E2E probe.",
  name: "E2EUtil",
};

describe("compareUnit (ADR-0033 item 2)", () => {
  it("finds nothing when the instance holds what the build would load", () => {
    const built = scriptInclude("Helpers for the E2E probe.");
    expect(compareUnit(built, copy(INSTANCE_SCRIPT_INCLUDE))).toEqual([]);
  });

  it("names each field the load would change, ignoring platform bookkeeping", () => {
    const built = scriptInclude("Helpers, edited in source.");
    expect(compareUnit(built, copy({ ...INSTANCE_SCRIPT_INCLUDE, sys_mod_count: "7" }))).toEqual([
      {
        kind: "field",
        table: "sys_script_include",
        row: "",
        field: "description",
        built: "Helpers, edited in source.",
        instance: "Helpers for the E2E probe.",
      },
    ]);
  });

  it("leaves fields the build omits unmanaged: a load does not touch them (S17)", () => {
    const built = scriptInclude("Helpers for the E2E probe.");
    const instance = copy({ ...INSTANCE_SCRIPT_INCLUDE, sandbox_callable: "true" });
    expect(compareUnit(built, instance)).toEqual([]);
  });

  it("ignores a field the instance has no column for: the load cannot set it", () => {
    const built = unit(
      "sys_choice_x_t_status",
      record("sys_choice_set", "f".repeat(32), {
        name: "x_t",
        element: "status",
        inactive_on_update: "false",
      }),
    );
    expect(compareUnit(built, copy({ name: "x_t", element: "status" }))).toEqual([]);
  });

  it("ignores a field the platform rewrites on save, such as an ACL's description", () => {
    const built = unit(
      "sys_security_acl_x",
      record("sys_security_acl", "a".repeat(32), {
        name: "incident",
        description: "Read incident",
      }),
    );
    expect(
      compareUnit(built, copy({ name: "incident", description: "Generated by the platform" })),
    ).toEqual([]);
  });

  it("treats line endings and trailing newlines as equal", () => {
    const built = scriptInclude("one\ntwo\n");
    expect(
      compareUnit(built, copy({ ...INSTANCE_SCRIPT_INCLUDE, description: "one\r\ntwo" })),
    ).toEqual([]);
  });

  it("reads the build's empty boolean as the instance's false", () => {
    const built = unit(
      "sys_dictionary_x_t_status",
      record("sys_dictionary", "d".repeat(32), { name: "x_t", element: "status", virtual: "" }),
    );
    expect(compareUnit(built, copy({ name: "x_t", element: "status", virtual: "false" }))).toEqual(
      [],
    );
  });

  it("compares a view by name: the build writes the default view as NULL", () => {
    expect(compareUnit(revocationList(["number"]), listCopy(["number"]))).toEqual([]);
  });

  it("compares a named view by name, whatever placeholder the build wrote", () => {
    const built = unit(
      "sys_ui_list_x_t_mobile",
      record(
        "sys_ui_list",
        "c".repeat(32),
        { name: "x_t", view: "e".repeat(32) },
        { view: "Mobile" },
      ),
    );
    const instance = copy({
      name: "x_t",
      view: "dd10f2738c1103100a22deb6dd2b4eee",
      "view.name": "Mobile",
    });
    expect(compareUnit(built, instance)).toEqual([]);
  });

  it("compares a list's columns as an ordered sequence, not by sys_id", () => {
    const built = revocationList(["number", "subject_user", "outcome"]);
    expect(compareUnit(built, listCopy(["number", "subject_user", "outcome"]))).toEqual([]);
    expect(compareUnit(built, listCopy(["subject_user", "number", "outcome"]))).toEqual([
      {
        kind: "rows",
        table: "sys_ui_list_element",
        built: ["number", "subject_user", "outcome"],
        instance: ["subject_user", "number", "outcome"],
      },
    ]);
  });

  it("matches choices by value and language, in any order, and compares their fields", () => {
    const choice = (sysId: string, value: string, label: string) =>
      record("sys_choice", sysId, { name: "x_t", element: "status", value, label, language: "en" });
    const built = unit(
      "sys_choice_x_t_status",
      record("sys_choice_set", "f".repeat(32), { name: "x_t", element: "status" }),
      [choice("1".repeat(32), "open", "Open"), choice("2".repeat(32), "closed", "Closed")],
    );
    const instance = copy({ name: "x_t", element: "status" }, [
      {
        sys_id: "9".repeat(32),
        name: "x_t",
        element: "status",
        value: "closed",
        label: "Done",
        language: "en",
      },
      {
        sys_id: "8".repeat(32),
        name: "x_t",
        element: "status",
        value: "open",
        label: "Open",
        language: "en",
      },
    ]);
    expect(compareUnit(built, instance)).toEqual([
      {
        kind: "field",
        table: "sys_choice",
        row: "closed|en",
        field: "label",
        built: "Closed",
        instance: "Done",
      },
    ]);
  });
});

describe("knownLoss (S16, S17)", () => {
  const field = (table: string, name: string, built: string, instance: string) =>
    ({ kind: "field", table, row: "", field: name, built, instance }) as const;

  it("names the SDK's API defaults", () => {
    expect(knownLoss(field("sys_script", "priority", "100", ""))).toBe("api-default");
    expect(
      knownLoss(
        field("sysevent_email_action", "digest_separator_html", "<p>&nbsp;</p>", "<br><hr><br>"),
      ),
    ).toBe("api-default");
  });

  it("names a reference written as its display value", () => {
    expect(
      knownLoss(field("sys_wizard_answer", "question", "Task", "dd21b6f78c5103100a22deb6dd2b4e61")),
    ).toBe("reference-display-value");
  });

  it("names a script the SDK only reformatted", () => {
    expect(
      knownLoss(
        field(
          "sys_ui_policy",
          "script_true",
          "function onCondition() {}",
          "function onCondition() {\n\n}",
        ),
      ),
    ).toBe("script-format");
  });

  it("names Form()'s column markers when the fields keep their order", () => {
    const rows = (built: string[], instance: string[]) =>
      ({ kind: "rows", table: "sys_ui_element", built, instance }) as const;
    expect(
      knownLoss(
        rows(
          [".begin_split|.begin_split", "number|", "state|", ".end_split|.end_split"],
          ["number|", "state|"],
        ),
      ),
    ).toBe("form-columns");
    expect(
      knownLoss(rows([".begin_split|.begin_split", "state|", "number|"], ["number|", "state|"])),
    ).toBeNull();
  });

  it("explains nothing else", () => {
    expect(knownLoss(field("sys_script_include", "description", "new", "old"))).toBeNull();
  });
});

describe("unit helpers", () => {
  it("finds a Now.del's record by the keys it names, and has no keys for one that names none", () => {
    const named = {
      ...unit(
        "sys_properties_x",
        record("sys_properties", "a".repeat(32), { sys_id: "a".repeat(32), name: "x.y" }),
      ),
    };
    const deletion = { ...named, head: { ...named.head, action: "DELETE" as const } };
    expect(coalesceValues(deletion)).toEqual({ name: "x.y" });
    const bare = { ...deletion, head: { ...deletion.head, fields: { sys_id: "a".repeat(32) } } };
    expect(coalesceValues(bare)).toBeNull();
  });

  it("names a unit by its record's name, or by its update name", () => {
    expect(unitName(unit("u1", record("sys_script", "a".repeat(32), { name: "Rule" })))).toBe(
      "Rule",
    );
    expect(
      unitName(unit("u2", record("sys_ui_list_element", "a".repeat(32), { position: "1" }))),
    ).toBe("u2");
  });
});

// B1 (spec 009): a change to protectionPolicy or useEsLatest alone must be seen as a change.
describe("compareUnit: protection policy and ES-latest mode (B1)", () => {
  const SI = "123833b4d97d48be8e9ec5ea16f27764";
  const withHead = (fields: Record<string, string>) => {
    const base = scriptInclude("Helpers for the E2E probe.");
    return { ...base, head: { ...base.head, fields: { ...base.head.fields, ...fields } } };
  };
  const esRow = (useEsLatest: string) =>
    record("sys_es_latest_script", "e".repeat(32), {
      sys_id: "e".repeat(32),
      id: SI,
      table: "sys_script_include",
      use_es_latest: useEsLatest,
    });
  const instanceEs = (useEsLatest: string) => ({
    sys_id: "e".repeat(32),
    id: SI,
    table: "sys_script_include",
    use_es_latest: useEsLatest,
  });

  it("names a protection policy the source changed", () => {
    const built = withHead({ sys_policy: "read" });
    expect(compareUnit(built, copy({ ...INSTANCE_SCRIPT_INCLUDE, sys_policy: "" }))).toEqual([
      expect.objectContaining({ field: "sys_policy", built: "read", instance: "" }),
    ]);
  });

  it("leaves the protection policy alone when the source sets none", () => {
    const built = scriptInclude("Helpers for the E2E probe.");
    expect(compareUnit(built, copy({ ...INSTANCE_SCRIPT_INCLUDE, sys_policy: "read" }))).toEqual(
      [],
    );
  });

  it("names an ES-latest mode the source changed", () => {
    const built = { ...scriptInclude("Helpers for the E2E probe."), children: [esRow("true")] };
    expect(compareUnit(built, copy(INSTANCE_SCRIPT_INCLUDE, [instanceEs("false")]))).toEqual([
      expect.objectContaining({
        table: "sys_es_latest_script",
        field: "use_es_latest",
        built: "true",
        instance: "false",
      }),
    ]);
  });

  it("finds nothing when the ES-latest mode agrees", () => {
    const built = { ...scriptInclude("Helpers for the E2E probe."), children: [esRow("true")] };
    expect(compareUnit(built, copy(INSTANCE_SCRIPT_INCLUDE, [instanceEs("true")]))).toEqual([]);
  });

  it("leaves the instance's ES-latest row alone when the source sets no mode", () => {
    const built = scriptInclude("Helpers for the E2E probe.");
    expect(compareUnit(built, copy(INSTANCE_SCRIPT_INCLUDE, [instanceEs("true")]))).toEqual([]);
  });

  it("names an ES-latest row the load would create", () => {
    const built = { ...scriptInclude("Helpers for the E2E probe."), children: [esRow("true")] };
    expect(compareUnit(built, copy(INSTANCE_SCRIPT_INCLUDE))).toEqual([
      expect.objectContaining({ kind: "rows", table: "sys_es_latest_script" }),
    ]);
  });
});

// B3 (spec 009): a role or view named in source builds as a placeholder sys_id with the name
// beside it; the instance holds the real sys_id. They are the same reference.
describe("compareUnit: roles and views named in source (B3)", () => {
  const PLACEHOLDER = "9e13c6b60dd04727b160d3e4569b4947";
  const REAL = "2831a114c611228501d4ea6c309d626d";
  const aclRole = (value: string, names: Record<string, string>) =>
    unit(
      "sys_security_acl_role_x",
      record("sys_security_acl_role", "a".repeat(32), { sys_user_role: value }, names),
    );

  it("compares an ACL's role by the role's name", () => {
    const built = aclRole(PLACEHOLDER, { sys_user_role: "admin" });
    const instance = copy({ sys_user_role: REAL, "sys_user_role.name": "admin" });
    expect(compareUnit(built, instance)).toEqual([]);
  });

  it("names a role the source changed", () => {
    const built = aclRole(PLACEHOLDER, { sys_user_role: "itil" });
    const instance = copy({ sys_user_role: REAL, "sys_user_role.name": "admin" });
    expect(compareUnit(built, instance)).toEqual([
      expect.objectContaining({ field: "sys_user_role", built: "itil", instance: "admin" }),
    ]);
  });

  it("compares by sys_id when the build names no role (keys.ts knew it)", () => {
    const built = aclRole(REAL, {});
    expect(
      compareUnit(built, copy({ sys_user_role: REAL, "sys_user_role.name": "admin" })),
    ).toEqual([]);
  });

  it("compares both sides of a role containment by name", () => {
    const built = unit(
      "sys_user_role_contains_x",
      record(
        "sys_user_role_contains",
        "b".repeat(32),
        { role: PLACEHOLDER, contains: "c".repeat(32) },
        { role: "x_app.approver", contains: "itil" },
      ),
    );
    const instance = copy({
      role: REAL,
      "role.name": "x_app.approver",
      contains: "d".repeat(32),
      "contains.name": "itil",
    });
    expect(compareUnit(built, instance)).toEqual([]);
  });

  it("compares a UI action's view by the view's name", () => {
    const built = unit(
      "sys_ui_action_view_x",
      record(
        "sys_ui_action_view",
        "e".repeat(32),
        { sys_ui_view: PLACEHOLDER },
        { sys_ui_view: "sys_ref_list" },
      ),
    );
    const instance = copy({ sys_ui_view: REAL, "sys_ui_view.name": "sys_ref_list" });
    expect(compareUnit(built, instance)).toEqual([]);
  });

  it("compares a field named role on another table as it is", () => {
    const built = unit("x_t_x", record("x_t", "f".repeat(32), { role: "admin" }));
    expect(compareUnit(built, copy({ role: "itil" }))).toEqual([
      expect.objectContaining({ field: "role", built: "admin", instance: "itil" }),
    ]);
  });
});

// A role hidden from the integration user (maint): the instance answers its sys_id but no name,
// while the build names it. The same sys_id is the same reference (spec 009 L1, pdi2).
describe("compareUnit: a named reference with the instance's own sys_id", () => {
  const REAL = "b05947ca0a0a0aa700fdef030c6bca07";
  const role = unit(
    "sys_security_acl_role_y",
    record(
      "sys_security_acl_role",
      "c".repeat(32),
      { sys_user_role: REAL },
      { sys_user_role: "maint" },
    ),
  );

  it("is the same reference whatever the names say", () => {
    expect(compareUnit(role, copy({ sys_user_role: REAL, "sys_user_role.name": "" }))).toEqual([]);
  });

  it("still names a different role", () => {
    expect(
      compareUnit(role, copy({ sys_user_role: "d".repeat(32), "sys_user_role.name": "admin" })),
    ).toEqual([
      expect.objectContaining({ field: "sys_user_role", built: "maint", instance: "admin" }),
    ]);
  });
});
